/**
 * Get icon color for a service name
 * @param {string} serviceName - The service name to look up
 * @returns {string|null} - The hex color or null if not found
 */
export function getIconColor(serviceName) {
  if (!serviceName) return null;
  const lower = serviceName.toLowerCase();

  // Exact match
  if (ALL_ICON_COLORS[lower]) {
    return ALL_ICON_COLORS[lower];
  }

  // Partial match
  for (const [key, color] of Object.entries(ALL_ICON_COLORS)) {
    if (lower.includes(key) || key.includes(lower)) {
      return color;
    }
  }

  return null;
}

