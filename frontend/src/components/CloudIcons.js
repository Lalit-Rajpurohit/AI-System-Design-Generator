/**
 * Inject cloud provider icons into rendered Mermaid SVG
 * @param {string} svgString - The rendered SVG from Mermaid
 * @returns {string} - SVG with icons injected into nodes
 */
export function injectCloudIcons(svgString) {
  if (!svgString || typeof window === 'undefined') return svgString;

  try {
    const parser = new DOMParser();
    const doc = parser.parseFromString(svgString, 'image/svg+xml');
    const svg = doc.querySelector('svg');

    if (!svg) return svgString;

    // Find all flowchart nodes - Mermaid v10 uses .node class
    const nodes = svg.querySelectorAll('g.node');

    nodes.forEach(node => {
      // Get all text content from the node to identify the service
      const allText = node.textContent || '';
      const labelText = allText.trim();

      if (!labelText) return;

      const iconColor = getIconColor(labelText);
      if (!iconColor) return;

      const category = getServiceCategory(labelText);

      // Find the shape element (rect or polygon)
      const rect = node.querySelector('rect');
      const polygon = node.querySelector('polygon');
      const shape = rect || polygon;

      if (!shape) return;

      // Get shape bounds
      let bounds;
      if (rect) {
        bounds = {
          x: parseFloat(rect.getAttribute('x')) || 0,
          y: parseFloat(rect.getAttribute('y')) || 0,
          width: parseFloat(rect.getAttribute('width')) || 100,
          height: parseFloat(rect.getAttribute('height')) || 50,
        };
      } else if (polygon) {
        const points = polygon.getAttribute('points') || '';
        const coords = points.split(/[\s,]+/).map(Number).filter(n => !isNaN(n));
        if (coords.length >= 4) {
          const xs = coords.filter((_, i) => i % 2 === 0);
          const ys = coords.filter((_, i) => i % 2 === 1);
          bounds = {
            x: Math.min(...xs),
            y: Math.min(...ys),
            width: Math.max(...xs) - Math.min(...xs),
            height: Math.max(...ys) - Math.min(...ys),
          };
        }
      }

      if (!bounds) return;

      // Create icon with proper SVG namespace
      const iconSize = Math.min(18, bounds.height * 0.45);
      const iconX = bounds.x + 6;
      const iconY = bounds.y + (bounds.height - iconSize) / 2;

      // Create icon elements using proper SVG namespace methods
      const iconGroup = document.createElementNS('http://www.w3.org/2000/svg', 'g');
      iconGroup.setAttribute('class', 'service-icon');
      iconGroup.setAttribute('transform', `translate(${iconX}, ${iconY})`);

      // Create icon background
      const iconBg = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
      iconBg.setAttribute('width', String(iconSize));
      iconBg.setAttribute('height', String(iconSize));
      iconBg.setAttribute('rx', '3');
      iconBg.setAttribute('fill', iconColor);

      // Create icon symbol based on category
      const iconSymbol = document.createElementNS('http://www.w3.org/2000/svg', 'g');
      iconSymbol.setAttribute('fill', '#FFFFFF');

      const symbolSize = iconSize * 0.5;
      const symbolOffset = (iconSize - symbolSize) / 2;

      if (category === 'database' || category === 'storage') {
        // Cylinder/storage icon
        const ellipse = document.createElementNS('http://www.w3.org/2000/svg', 'ellipse');
        ellipse.setAttribute('cx', String(iconSize / 2));
        ellipse.setAttribute('cy', String(iconSize * 0.35));
        ellipse.setAttribute('rx', String(symbolSize * 0.7));
        ellipse.setAttribute('ry', String(symbolSize * 0.25));
        ellipse.setAttribute('fill', '#FFFFFF');

        const body = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
        body.setAttribute('x', String(iconSize / 2 - symbolSize * 0.7));
        body.setAttribute('y', String(iconSize * 0.35));
        body.setAttribute('width', String(symbolSize * 1.4));
        body.setAttribute('height', String(symbolSize * 0.8));
        body.setAttribute('fill', '#FFFFFF');
        body.setAttribute('opacity', '0.8');

        iconSymbol.appendChild(body);
        iconSymbol.appendChild(ellipse);
      } else if (category === 'compute') {
        // Server/compute icon
        const box = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
        box.setAttribute('x', String(symbolOffset));
        box.setAttribute('y', String(symbolOffset));
        box.setAttribute('width', String(symbolSize));
        box.setAttribute('height', String(symbolSize));
        box.setAttribute('rx', '2');
        box.setAttribute('fill', '#FFFFFF');
        iconSymbol.appendChild(box);
      } else if (category === 'network') {
        // Network/diamond icon
        const circle = document.createElementNS('http://www.w3.org/2000/svg', 'circle');
        circle.setAttribute('cx', String(iconSize / 2));
        circle.setAttribute('cy', String(iconSize / 2));
        circle.setAttribute('r', String(symbolSize * 0.5));
        circle.setAttribute('fill', '#FFFFFF');
        iconSymbol.appendChild(circle);
      } else if (category === 'messaging' || category === 'cache') {
        // Queue icon
        const arrow = document.createElementNS('http://www.w3.org/2000/svg', 'path');
        const ax = iconSize * 0.25;
        const ay = iconSize * 0.4;
        const aw = iconSize * 0.5;
        const ah = iconSize * 0.2;
        arrow.setAttribute('d', `M${ax} ${ay}h${aw}v${ah}H${ax}z`);
        arrow.setAttribute('fill', '#FFFFFF');
        iconSymbol.appendChild(arrow);
      } else if (category === 'security') {
        // Shield icon
        const shield = document.createElementNS('http://www.w3.org/2000/svg', 'path');
        const sx = iconSize / 2;
        const sy = iconSize * 0.25;
        const sw = symbolSize * 0.4;
        const sh = symbolSize * 0.6;
        shield.setAttribute('d', `M${sx} ${sy}l${sw} ${sh*0.3}v${sh*0.4}c0 ${sh*0.2}-${sw} ${sh*0.3}-${sw} ${sh*0.3}s-${sw}-${sh*0.1}-${sw}-${sh*0.3}V${sy+sh*0.3}z`);
        shield.setAttribute('fill', '#FFFFFF');
        iconSymbol.appendChild(shield);
      } else {
        // Generic circle icon
        const circle = document.createElementNS('http://www.w3.org/2000/svg', 'circle');
        circle.setAttribute('cx', String(iconSize / 2));
        circle.setAttribute('cy', String(iconSize / 2));
        circle.setAttribute('r', String(symbolSize * 0.4));
        circle.setAttribute('fill', '#FFFFFF');
        iconSymbol.appendChild(circle);
      }

      iconGroup.appendChild(iconBg);
      iconGroup.appendChild(iconSymbol);

      // Insert icon into the node
      // Try multiple insertion strategies for Mermaid v10 compatibility
      try {
        // Strategy 1: Insert after shape
        if (shape.parentNode) {
          shape.parentNode.appendChild(iconGroup);
        }
      } catch (insertErr) {
        console.warn('Icon insertion failed:', insertErr);
      }

      // Also add a colored left border to the shape as visual indicator
      if (rect) {
        // Add a colored left edge indicator
        const indicator = document.createElementNS('http://www.w3.org/2000/svg', 'rect');
        indicator.setAttribute('x', String(bounds.x));
        indicator.setAttribute('y', String(bounds.y));
        indicator.setAttribute('width', '4');
        indicator.setAttribute('height', String(bounds.height));
        indicator.setAttribute('fill', iconColor);
        indicator.setAttribute('rx', '2');

        if (rect.parentNode) {
          rect.parentNode.insertBefore(indicator, rect);
        }
      }
    });

    return new XMLSerializer().serializeToString(svg);
  } catch (err) {
    console.error('Icon injection error:', err);
    return svgString;
  }
}

